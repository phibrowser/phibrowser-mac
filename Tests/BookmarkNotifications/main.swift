// Observe actual Core Data notifications generated by SwiftData. Never retain
// NSManagedObjects across threads and never post a synthetic notification.
final class SaveRecorder: @unchecked Sendable {
    private let lock = NSLock()
    private var will: [ObjectIdentifier: [String: [String]]] = [:]
    private var events: [[String: Any]] = []
    private var observers: [NSObjectProtocol] = []
    init() {
        observers.append(NotificationCenter.default.addObserver(forName: .NSManagedObjectContextWillSave,
            object: nil, queue: nil) { [weak self] n in
            guard let self, let context = n.object as? NSManagedObjectContext else { return }
            let values = Dictionary(uniqueKeysWithValues: context.updatedObjects.compactMap { object -> (String, [String])? in
                guard object.entity.name == TabDataModel.entityName,
                      let guid = object.value(forKey: "guid") as? String else { return nil }
                return (guid, object.changedValues().keys.sorted())
            })
            self.lock.lock(); self.will[ObjectIdentifier(context)] = values; self.lock.unlock()
        })
        observers.append(NotificationCenter.default.addObserver(forName: .NSManagedObjectContextDidSave,
            object: nil, queue: nil) { [weak self] n in
            guard let self, let context = n.object as? NSManagedObjectContext else { return }
            var entries: [[String: String]] = []
            for (key, kind) in [(NSInsertedObjectsKey, "insert"), (NSUpdatedObjectsKey, "update"), (NSDeletedObjectsKey, "delete")] {
                for object in n.userInfo?[key] as? Set<NSManagedObject> ?? [] where object.entity.name == TabDataModel.entityName {
                    entries.append(["kind": kind, "guid": object.value(forKey: "guid") as? String ?? "unknown"])
                }
            }
            guard !entries.isEmpty else { return }
            self.lock.lock()
            self.events.append(["rows": entries.sorted { $0["guid"]! < $1["guid"]! },
                "changed_keys_before_save": self.will[ObjectIdentifier(context)] ?? [:],
                "on_main_thread": Thread.isMainThread,
                "context_id": String(describing: ObjectIdentifier(context)),
                "private_queue_context": context.concurrencyType == .privateQueueConcurrencyType])
            self.lock.unlock()
        })
    }
    deinit { observers.forEach(NotificationCenter.default.removeObserver) }
    func reset() { lock.lock(); events.removeAll(); will.removeAll(); lock.unlock() }
    func snapshot() -> [[String: Any]] { lock.lock(); defer { lock.unlock() }; return events }
}

@MainActor final class Receiver {
    let name: String
    var callbacks = 0
    var metadataCallbacks = 0
    let projection = VisitProjection()
    var lastRows: [String] = []
    var lastValues: [String: [String: Any]] = [:]
    var subscription: AnyCancellable?
    var allCallbacksOnMainThread = true
    init(_ store: LocalStore, profile: String, space: String, name: String) {
        self.name = name
        subscription = store.bookmarksPublisher(profileId: profile, spaceId: space, onLastSeenChange: { [weak self] rows in
            guard let self else { return }
            self.metadataCallbacks += 1
            self.allCallbacksOnMainThread = self.allCallbacksOnMainThread && Thread.isMainThread
            self.projection.consume(rows)
            for row in rows {
                self.lastValues[row.guid]?["lastSeen"] = row.lastSeen.map { $0.timeIntervalSince1970 as Any } ?? NSNull()
            }
        }).sink { [weak self] rows in
            self?.callbacks += 1
            self?.projection.replace(rows)
            self?.allCallbacksOnMainThread = (self?.allCallbacksOnMainThread ?? true) && Thread.isMainThread
            self?.lastRows = rows.map(\.guid).sorted()
            self?.lastValues = Dictionary(uniqueKeysWithValues: rows.map { row in
                (row.guid, ["title": row.title, "url": row.url.absoluteString,
                    "lastSeen": row.lastSeen.map { $0.timeIntervalSince1970 as Any } ?? NSNull(),
                    "parent": row.parent?.guid as Any? ?? NSNull()] as [String: Any])
            })
        }
    }
}

