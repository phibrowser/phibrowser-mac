// The manager seam compiles its production visit-update method against a minimal
// in-memory Bookmark. It exercises indexed updates, not AppKit or tree projection.
final class Bookmark {
    let guid: String
    let isFolder: Bool
    var lastSeen: Date?
    init(_ row: TabDataModel) { guid = row.guid; isFolder = row.type == 3; lastSeen = row.lastSeen }
}
@MainActor final class VisitProjection {
    var bookmarkIndex: [String: Bookmark] = [:]
    var changedDates = 0
    func replace(_ rows: [TabDataModel]) {
        bookmarkIndex = Dictionary(uniqueKeysWithValues: rows.map { ($0.guid, Bookmark($0)) })
    }
    func consume(_ rows: [TabDataModel]) {
        let old = rows.map { bookmarkIndex[$0.guid]?.lastSeen }
        applyLastSeenUpdates(from: rows)
        changedDates += zip(rows, old).filter { bookmarkIndex[$0.0.guid]?.lastSeen != $0.1 }.count
    }
    /* PRODUCTION_VISIT_PROJECTION */
}


@MainActor final class QueryContext {
    let real: ModelContext
    var fetches = 0
    var failNextFetch = false
    var rowsFetched = 0
    var allFetchesOnMainThread = true
    init(_ real: ModelContext) { self.real = real }
    func fetch(_ descriptor: FetchDescriptor<TabDataModel>) throws -> [TabDataModel] {
        fetches += 1
        if failNextFetch { failNextFetch = false; throw NSError(domain: "TestInjectedFetchFailure", code: 1) }
        allFetchesOnMainThread = allFetchesOnMainThread && Thread.isMainThread
        let rows = try real.fetch(descriptor)
        rowsFetched += rows.count
        return rows
    }
}

